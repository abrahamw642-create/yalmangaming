/**
 * Expected-FPS figures for the "Performance" table on a graphics card's page.
 *
 * Rules this list is written under, because the storefront renders these
 * numbers as fact:
 *   - GPUs only. There is no honest per-CPU frame rate to publish yet.
 *   - Every figure is a native-resolution average with upscaling and frame
 *     generation OFF, and ray tracing off unless the preset says otherwise.
 *     Folding an upscaled number into this table would flatter the cheaper
 *     cards and mislead someone sizing a build around it.
 *   - Where a realistic figure is not known, the row is simply absent. The
 *     product page renders the rows that exist and nothing more, so a short
 *     table is correct where an invented row would not be.
 *   - `source` is identical on every row and says plainly that these are
 *     aggregated third-party figures Yalman has not re-measured in store yet.
 */

export type SeedBenchmark = {
  /** `slug` of the graphics card in `gpus` above. */
  productSlug: string;
  game: string;
  /** 1080p | 1440p | 4K */
  resolution: string;
  /** Low | Medium | High | Ultra */
  preset: string;
  avgFps: number;
  onePercentLow: number;
  /** The processor the figure was recorded with — it bounds the result. */
  cpuContext: string;
};

/** Attribution carried by every row. Never omit it. */
export const BENCHMARK_SOURCE =
  "Manufacturer and press aggregate — pending Yalman in-store verification";

/**
 * Reviewers benchmark with the fastest gaming CPU available so that the card is
 * the only variable. Recording that here keeps the esports figures honest: 600
 * FPS in CS2 is a property of this pairing, not of the card on its own.
 */
const REF_CPU = "AMD Ryzen 7 9800X3D";

function bench(
  productSlug: string,
  game: string,
  resolution: string,
  preset: string,
  avgFps: number,
  onePercentLow: number,
): SeedBenchmark {
  return {
    productSlug,
    game,
    resolution,
    preset,
    avgFps,
    onePercentLow,
    cpuContext: REF_CPU,
  };
}

