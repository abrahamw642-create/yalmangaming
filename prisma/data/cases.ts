/**
 * PC cases.
 *
 * Every dimension here is a real published clearance, because the case is where
 * builds actually fail. The engine reads:
 *   supportedFormFactors -> hard error if the board does not appear in the list
 *   maxGpuLengthMm       -> hard error if the card is longer; a warning when
 *                           fewer than 15mm are left
 *   maxCoolerHeightMm    -> hard error for a taller air cooler
 *   radiatorSupport      -> hard error if the AIO radiator exceeds every mount
 *   maxPsuLengthMm       -> hard error for a deeper power supply
 *   includedFans         -> a warning when the case ships with none and no fans
 *                           have been added
 *   caseStyle            -> "Mini ITX" triggers the ATX-power-supply caution
 *   dimensionsMm         -> "W x D x H"; a large footprint raises an info note
 *
 * The small chassis in this list genuinely cannot take a 350mm graphics card,
 * and the Q300L V2 genuinely will not take an ATX board. Those are not
 * contrived — they are the two mistakes customers make most often.
 */

