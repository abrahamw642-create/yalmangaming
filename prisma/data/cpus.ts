/**
 * Processors.
 *
 * `socket`, `tdp` and `integratedGraphics` are load-bearing for the
 * compatibility engine:
 *   socket             -> CPU/motherboard match, and cooler mounting hardware
 *   tdp                -> power estimate (multiplied by 1.35 for boost) and the
 *                         "cooler may not keep up" warning
 *   integratedGraphics -> the "no display output" error when no GPU is picked
 *
 * On integrated graphics specifically: every AM5 Ryzen desktop part — X3D
 * included — ships with a small RDNA 2 display adapter, so those are `true`.
 * The parts that genuinely have no display output are the AM4 non-G Ryzens and
 * Intel's F-suffix SKUs, and they are marked `false` here. That is what makes
 * the engine's `no-display-output` rule fire on a real configuration rather
 * than a fabricated one.
 *
 * Clocks are in GHz. For Intel's hybrid parts `baseClock`/`boostClock` are the
 * P-core figures, and `cores` counts P + E cores.
 */

